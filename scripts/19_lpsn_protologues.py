"""Original descriptions (protologues) of the low-confidence Alicyclobacillaceae / Sulfolobaceae species, from LPSN (DSMZ, open).
Output: data/curated/protologue_reading_list.csv  (one row per species: LPSN name, type strain designations, valid publication, DOI),
and docs/PRIMARY_SOURCES_NEEDED.md (species grouped by paper). Usage: python3 scripts/19_lpsn_protologues.py"""
import html
import re
import time
import urllib.request
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
tg = pd.read_csv(ROOT / "results/within_lineage_v2/primary_source_targets.csv")
ALIAS = {"Saccharolobus solfataricus": ["Sulfolobus solfataricus", "Saccharolobus solfataricus"], "Saccharolobus shibatae": ["Sulfolobus shibatae", "Saccharolobus shibatae"],
         "Sulfolobus tokodaii": ["Sulfolobus tokodaii", "Sulfurisphaera tokodaii"], "Alicyclobacillus acidocaldarius": ["Alicyclobacillus acidocaldarius", "Bacillus acidocaldarius"],
         "Alicyclobacillus acidoterrestris": ["Alicyclobacillus acidoterrestris", "Bacillus acidoterrestris"], "Alicyclobacillus cycloheptanicus": ["Alicyclobacillus cycloheptanicus", "Bacillus cycloheptanicus"],
         "Metallosphaera hakonensis": ["Metallosphaera hakonensis", "Sulfolobus hakonensis"], "Sulfolobus metallicus": ["Sulfolobus metallicus", "Sulfuracidifex metallicus"]}


def page(slug):
    try:
        return urllib.request.urlopen(urllib.request.Request("https://lpsn.dsmz.de/species/" + slug, headers={"User-Agent": "Mozilla/5.0"}), timeout=40).read().decode("utf8", "ignore")
    except Exception:
        return None


rows = []
for r in tg.itertuples():
    got = None
    for nm in ALIAS.get(r.species, [r.species]):
        h = page(nm.lower().replace(" ", "-")); time.sleep(0.8)
        if h and "Valid publication" in h:
            got = (nm, h); break
    if not got:
        rows.append({"species": r.species, "lpsn_name": "", "type_strain": "", "valid_publication": "NOT FOUND ON LPSN (candidate name or unrecognised)", "doi": "", "database_value": f"{r.ph_min}-{r.ph_max} (opt {r.ph_opt})", "origin": r.origin}); continue
    nm, h = got
    txt = html.unescape(re.sub(r"\s+", " ", re.sub(r"<script.*?</script>|<style.*?</style>|<[^>]+>", " ", h, flags=re.S)))
    pub = re.search(r"Valid publication: (.*?) (?:🇩🇪|Nomenclatural status)", txt)
    ts = re.search(r"Type strain: (.*?) See detailed", txt)
    block = h[h.find("Valid publication"):h.find("Valid publication") + 3000]
    doi = re.search(r"10\.\d{4,9}/[^\s\"<>)&]+", block)
    nomen = re.search(r"Name: (.*?) Category", txt)
    rows.append({"species": r.species, "lpsn_name": (nomen.group(1) if nomen else nm).strip(), "type_strain": ts.group(1).strip() if ts else "", "valid_publication": pub.group(1).strip() if pub else "",
                 "doi": doi.group(0).rstrip(".,;") if doi else "", "database_value": f"{r.ph_min}-{r.ph_max} (opt {r.ph_opt})", "origin": r.origin})
D = pd.DataFrame(rows)
D.to_csv(ROOT / "data/curated/protologue_reading_list.csv", index=False)
print(len(D), "species |", int((D.valid_publication.str.startswith("NOT FOUND")).sum()), "not found on LPSN |", D[D.doi != ""].doi.nunique(), "distinct papers with a DOI")

# ---- reading list document ----
done = {"Alicyclobacillus curvatus", "Alicyclobacillus mengziensis", "Alicyclobacillus sendaiensis"}   # already entered from open sources
R = D[~D.species.isin(done)].fillna("")


def basonym(name):
    m = re.search(r"\(([^()]*\d{4})\)\s+[A-Z]", name)
    return m.group(1) if m else ""


L = ["# Primary sources still needed (Alicyclobacillaceae and Sulfolobaceae)", "",
     "Generated by `scripts/19_lpsn_protologues.py` from LPSN (DSMZ) and the ThermoBase source links. Publisher sites (Microbiology Society, ScienceDirect, Springer) serve bot challenges, so their full texts were not retrieved. Open sources already supplied three species (*A. curvatus* and *A. mengziensis* from the open-access protologue; *A. sendaiensis* from its abstract).", "",
     "For each paper, please read the species description and Methods and record: (1) growth pH range, (2) optimum, (3) **the lowest pH tested and whether growth failed below the reported minimum** (this upgrades a database value to a verified limit), (4) the type strain and its culture-collection numbers.", "",
     "## A. Papers with a DOI (one paper can cover several species)", ""]
for doi, x in sorted(R[R.doi != ""].groupby("doi"), key=lambda kv: -len(kv[1])):
    pub = x.valid_publication.iloc[0]
    pub_year = (re.search(r"(\d{4});\s*\d+\s*:", pub) or [None, ""])[1]
    L += [f"### https://doi.org/{doi}  ({len(x)} species)", pub, ""]
    for r in x.itertuples():
        b = basonym(r.lpsn_name)
        by = (re.search(r"(\d{4})", b) or [None, ""])[1]
        need = f"; **also needs the original description of the basonym ({b})**" if (b and by != pub_year) else ""
        L.append(f"- *{r.species}* — database value pH {r.database_value} ({r.origin})" + (f"; type strain {r.type_strain}" if r.type_strain else "") + need)
    L.append("")
L += ["## B. Species not found on LPSN (not validly published, candidate names, or slug mismatch): identify the original description first", ""]
L += [f"- *{r.species}* — database value pH {r.database_value} ({r.origin})" for r in R[R.doi == ""].itertuples()]
L += ["", "## Notes",
      "- For species whose LPSN valid publication is a transfer (comb. nov.), the pH range normally appears in the *original* description, not the transfer paper.",
      "- Some ThermoBase links point to reviews, genome reports or web pages (a course page for *A. ambivalens*, a BioCyc page for *M. yellowstonensis*, a genus-level statement in the *A. hospitalis* genome report), so those values are not traceable to a species description.",
      "- The ThermoBase link for *A. cycloheptanicus*, *A. acidocaldarius* and *A. acidoterrestris* is the 1992 genus-proposal paper (10.1099/00207713-42-2-263), a 16S rRNA analysis that is unlikely to be the source of the pH ranges."]
(ROOT / "docs/PRIMARY_SOURCES_NEEDED.md").write_text("\n".join(L) + "\n")
print("wrote docs/PRIMARY_SOURCES_NEEDED.md")
